-- Um único resumo atual por ativo; novas execuções substituem o conteúdo.
CREATE TABLE IF NOT EXISTS resumos_ativos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id INTEGER NOT NULL REFERENCES ativos(id),
    resumo TEXT NOT NULL,
    fontes TEXT NOT NULL DEFAULT '',
    modelo VARCHAR(120),
    status VARCHAR(30) NOT NULL DEFAULT 'GERADO',
    gerado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    erro TEXT,
    CONSTRAINT uix_resumos_ativos_ativo UNIQUE (ativo_id)
);

CREATE INDEX IF NOT EXISTS ix_resumos_ativos_ativo_id
    ON resumos_ativos (ativo_id);
